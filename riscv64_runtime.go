package main

import "math"

// emitStart runs the top level and exits with the value of its last expression.
func (g *rvGen) emitStart() {
	skip := g.newLabel()
	if g.dynamic {
		noFini := g.newLabel()
		g.beqz(rvA0, noFini)
		g.li(rvA1, 0)
		g.li(rvA2, 0)
		g.callC("__cxa_atexit")
		g.bind(noFini)
		g.la(rvT0, g.importSlot("stdout"))
		g.ld(rvT0, rvT0, 0)
		g.ld(rvA0, rvT0, 0)
		g.li(rvA1, 0)
		g.li(rvA2, 2)
		g.li(rvA3, 0)
		g.callC("setvbuf")
	}
	g.la(rvS1, g.l["globals"])
	g.li(rvT0, 1)
	g.la(rvT1, g.l["outfd"])
	g.sd(rvT0, rvT1, 0)
	g.addi(rvSP, rvSP, -64)
	g.li(rvA0, 1)
	g.li(rvA1, 0x5401)
	g.mv(rvA2, rvSP)
	g.li(rvA7, 29)
	g.ecall()
	g.addi(rvSP, rvSP, 64)
	g.sltiu(rvA0, rvA0, 1)
	g.la(rvT1, g.l["outtty"])
	g.sd(rvA0, rvT1, 0)
	g.call(g.l["main"])
	g.li(rvS2, 0)
	g.feq(rvT0, rvFA0, rvFA0)
	g.beqz(rvT0, skip)
	g.fcvtLD(rvS2, rvFA0, 1)
	g.bind(skip)
	g.mv(rvA0, rvS2)
	g.exitWith()
}

// exitWith flushes Tim's output and exits with the status in a0: through
// libc's exit when C is linked in (so C stdio is flushed too), otherwise
// with exit_group.
func (g *rvGen) exitWith() {
	g.mv(rvS2, rvA0)
	g.call(g.l["flush"])
	g.mv(rvA0, rvS2)
	if g.dynamic {
		g.callC("exit")
	}
	g.li(rvA7, 94)
	g.ecall()
}

func (g *rvGen) emitHelpers() {
	l := g.l

	// num(a0 = op, fa0, fa1) -> fa0
	g.bind(l["num"])
	g.addi(rvSP, rvSP, -16)
	g.sd(rvRA, rvSP, 8)
	g.fmvXD(rvA1, rvFA0)
	g.fmvXD(rvA2, rvFA1)
	g.la(rvA3, l["alloc"])
	g.li(rvA4, 0)
	g.jal(rvRA, l["blob"], numRuntimeRISCV64Entry)
	g.fmvDX(rvFA0, rvA0)
	g.ld(rvRA, rvSP, 8)
	g.addi(rvSP, rvSP, 16)
	g.ret()

	// alloc(ctx, a1 = size) -> a0: bump allocation from mmap'd chunks.
	g.bind(l["alloc"])
	grow, skip := g.newLabel(), g.newLabel()
	g.addi(rvA1, rvA1, 15)
	g.andi(rvA1, rvA1, -16)
	g.la(rvT0, l["heap"])
	g.ld(rvT1, rvT0, 0)
	g.ld(rvT2, rvT0, 8)
	g.add(rvT3, rvT1, rvA1)
	g.br(6, rvT2, rvT3, grow)
	g.sd(rvT3, rvT0, 0)
	g.mv(rvA0, rvT1)
	g.ret()
	g.bind(grow)
	g.mv(rvT4, rvA1)
	g.li(rvT5, 64<<20)
	g.br(7, rvT5, rvT4, skip)
	g.mv(rvT5, rvT4)
	g.bind(skip)
	g.mv(rvA1, rvT5)
	g.li(rvA0, 0)
	g.li(rvA2, 3)
	g.li(rvA3, 0x22)
	g.li(rvA4, -1)
	g.li(rvA5, 0)
	g.li(rvA7, 222)
	g.ecall()
	g.add(rvT2, rvA0, rvT5)
	g.sd(rvT2, rvT0, 8)
	g.add(rvT3, rvA0, rvT4)
	g.sd(rvT3, rvT0, 0)
	g.ret()

	// putc(a0): buffered output to outfd, flushed per line on a terminal.
	// Clobbers t0-t2, a0-a2, a7.
	g.bind(l["putc"])
	done := g.newLabel()
	g.la(rvT0, l["outlen"])
	g.ld(rvT1, rvT0, 0)
	g.la(rvT2, l["outbuf"])
	g.add(rvT2, rvT2, rvT1)
	g.sb(rvA0, rvT2, 0)
	g.addi(rvT1, rvT1, 1)
	g.sd(rvT1, rvT0, 0)
	g.li(rvT2, 4096)
	full := g.newLabel()
	g.br(7, rvT1, rvT2, full)
	g.li(rvT2, '\n')
	g.br(1, rvA0, rvT2, done)
	g.la(rvT2, l["outtty"])
	g.ld(rvT2, rvT2, 0)
	g.beqz(rvT2, done)
	g.bind(full)
	g.j(l["flush"])
	g.bind(done)
	g.ret()

	g.bind(l["flush"])
	done = g.newLabel()
	g.la(rvT0, l["outlen"])
	g.ld(rvA2, rvT0, 0)
	g.beqz(rvA2, done)
	g.la(rvT1, l["outfd"])
	g.ld(rvA0, rvT1, 0)
	g.la(rvA1, l["outbuf"])
	g.li(rvA7, 64)
	g.ecall()
	g.sd(0, rvT0, 0)
	g.bind(done)
	g.ret()

	// print_raw(a0 = bytes, a1 = len)
	g.bind(l["print_raw"])
	loop, done := g.newLabel(), g.newLabel()
	g.addi(rvSP, rvSP, -16)
	g.sd(rvRA, rvSP, 8)
	g.mv(rvT3, rvA1)
	g.mv(rvT4, rvA0)
	g.bind(loop)
	g.beqz(rvT3, done)
	g.lbu(rvA0, rvT4, 0)
	g.call(l["putc"])
	g.addi(rvT4, rvT4, 1)
	g.addi(rvT3, rvT3, -1)
	g.j(loop)
	g.bind(done)
	g.ld(rvRA, rvSP, 8)
	g.addi(rvSP, rvSP, 16)
	g.ret()

	// print_val(fa0): any value, as println shows it.
	g.bind(l["print_val"])
	g.addi(rvSP, rvSP, -16)
	g.sd(rvRA, rvSP, 8)
	g.li(rvA0, valUTF8)
	g.call(l["num"])
	g.fmvXD(rvA0, rvFA0)
	g.ld(rvA1, rvA0, 0)
	g.addi(rvA0, rvA0, 8)
	g.call(l["print_raw"])
	g.ld(rvRA, rvSP, 8)
	g.addi(rvSP, rvSP, 16)
	g.ret()

	// print_i64(a0)
	g.bind(l["print_i64"])
	pos, digits, out, done := g.newLabel(), g.newLabel(), g.newLabel(), g.newLabel()
	g.addi(rvSP, rvSP, -48)
	g.sd(rvRA, rvSP, 40)
	g.mv(rvT3, rvA0)
	g.br(5, rvT3, 0, pos)
	g.li(rvA0, '-')
	g.call(l["putc"])
	g.op(0x20, 0, rvT3, 0, rvT3)
	g.bind(pos)
	g.addi(rvT4, rvSP, 32)
	g.li(rvT5, 10)
	g.bind(digits)
	g.op(1, 7, rvT6, rvT3, rvT5)
	g.op(1, 5, rvT3, rvT3, rvT5)
	g.addi(rvT6, rvT6, '0')
	g.addi(rvT4, rvT4, -1)
	g.sb(rvT6, rvT4, 0)
	g.bnez(rvT3, digits)
	g.bind(out)
	g.addi(rvT5, rvSP, 32)
	g.br(0, rvT4, rvT5, done)
	g.lbu(rvA0, rvT4, 0)
	g.call(l["putc"])
	g.addi(rvT4, rvT4, 1)
	g.j(out)
	g.bind(done)
	g.ld(rvRA, rvSP, 40)
	g.addi(rvSP, rvSP, 48)
	g.ret()

	// print_hex(a0, a1 = letter base - 10)
	g.bind(l["print_hex"])
	digits, out, done = g.newLabel(), g.newLabel(), g.newLabel()
	letter := g.newLabel()
	g.addi(rvSP, rvSP, -48)
	g.sd(rvRA, rvSP, 40)
	g.mv(rvT3, rvA0)
	g.addi(rvT4, rvSP, 32)
	g.bind(digits)
	g.andi(rvT6, rvT3, 15)
	g.srli(rvT3, rvT3, 4)
	g.li(rvT5, 10)
	g.br(5, rvT6, rvT5, letter)
	g.addi(rvT6, rvT6, '0'-0)
	g.addi(rvT4, rvT4, -1)
	g.sb(rvT6, rvT4, 0)
	g.bnez(rvT3, digits)
	g.j(out)
	g.bind(letter)
	g.add(rvT6, rvT6, rvA1)
	g.addi(rvT4, rvT4, -1)
	g.sb(rvT6, rvT4, 0)
	g.bnez(rvT3, digits)
	g.bind(out)
	g.addi(rvT5, rvSP, 32)
	g.br(0, rvT4, rvT5, done)
	g.lbu(rvA0, rvT4, 0)
	g.call(l["putc"])
	g.addi(rvT4, rvT4, 1)
	g.j(out)
	g.bind(done)
	g.ld(rvRA, rvSP, 40)
	g.addi(rvSP, rvSP, 48)
	g.ret()

	// print_fixed(fa0, a0 = precision): fixed-point with round-to-nearest-even digits.
	g.bind(l["print_fixed"])
	pos, pow, carry, frac, done := g.newLabel(), g.newLabel(), g.newLabel(), g.newLabel(), g.newLabel()
	g.addi(rvSP, rvSP, -48)
	g.sd(rvRA, rvSP, 40)
	g.fsd(rvFS0, rvSP, 32)
	g.sd(rvS2, rvSP, 24)
	g.sd(rvS3, rvSP, 16)
	g.fmvD(rvFS0, rvFA0)
	g.mv(rvS2, rvA0)
	g.fmvDX(rvFT0, 0)
	g.fop(0x51, 1, rvT0, rvFS0, rvFT0)
	g.beqz(rvT0, pos)
	g.li(rvA0, '-')
	g.call(l["putc"])
	g.fop(0x11, 1, rvFS0, rvFS0, rvFS0)
	g.bind(pos)
	g.fcvtLD(rvS3, rvFS0, 1)
	g.li(rvT0, 1)
	g.li(rvT2, 10)
	g.bind(pow)
	g.beqz(rvS2, carry)
	g.op(1, 0, rvT0, rvT0, rvT2)
	g.addi(rvS2, rvS2, -1)
	g.j(pow)
	g.bind(carry)
	g.fcvtDL(rvFT1, rvS3)
	g.fop(0x05, 7, rvFT1, rvFS0, rvFT1)
	g.fcvtDL(rvFT2, rvT0)
	g.fop(0x09, 7, rvFT1, rvFT1, rvFT2)
	g.fcvtLD(rvT1, rvFT1, 0)
	g.br(6, rvT1, rvT0, frac)
	g.addi(rvS3, rvS3, 1)
	g.op(0x20, 0, rvT1, rvT1, rvT0)
	g.bind(frac)
	g.sd(rvT0, rvSP, 8)
	g.sd(rvT1, rvSP, 0)
	g.mv(rvA0, rvS3)
	g.call(l["print_i64"])
	g.ld(rvS2, rvSP, 8)
	g.ld(rvS3, rvSP, 0)
	g.li(rvT0, 1)
	g.br(0, rvS2, rvT0, done)
	g.li(rvA0, '.')
	g.call(l["putc"])
	loop = g.newLabel()
	g.bind(loop)
	g.li(rvT0, 10)
	g.op(1, 5, rvS2, rvS2, rvT0)
	g.beqz(rvS2, done)
	g.op(1, 5, rvA0, rvS3, rvS2)
	g.op(1, 7, rvA0, rvA0, rvT0)
	g.addi(rvA0, rvA0, '0')
	g.call(l["putc"])
	g.j(loop)
	g.bind(done)
	g.ld(rvRA, rvSP, 40)
	g.fld(rvFS0, rvSP, 32)
	g.ld(rvS2, rvSP, 24)
	g.ld(rvS3, rvSP, 16)
	g.addi(rvSP, rvSP, 48)
	g.ret()
}

// boxTest branches to notBox unless the bits in r are a container pointer
// (a positive denormal). Clobbers scratch.
func (g *rvGen) boxTest(r, scratch uint32, notBox *rvLabel) {
	g.addi(scratch, r, -1)
	g.srli(scratch, scratch, 52)
	g.bnez(scratch, notBox)
}

// seqTest branches to no unless the bits in r are a string, list or map.
func (g *rvGen) seqTest(r, scratch uint32, no *rvLabel) {
	g.boxTest(r, scratch, no)
	g.ld(scratch, r, 0)
	g.srli(scratch, scratch, 48)
	g.li(rvT6, int64(math.Float64bits(4.0)>>48))
	g.br(7, scratch, rvT6, no)
}

// selectOutput flushes stdout and routes further output to fd.
func (g *rvGen) selectOutput(fd int64) {
	g.call(g.l["flush"])
	g.li(rvT0, fd)
	g.la(rvT1, g.l["outfd"])
	g.sd(rvT0, rvT1, 0)
}
